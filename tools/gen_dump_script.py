"""Generate gm9/scripts/dump_system_apps.gm9 from the title list below.

Usage:
    python3 -m tools.gen_dump_script           write the script
    python3 -m tools.gen_dump_script --check   only check that the committed
                                               script is up to date

Written for GodMode9 v2.2.3 script syntax (checked against its source).
Edit this file, not the .gm9. Every run also checks the generated script's
structure (see check()); a change that breaks a rule is not written.
"""
import os
import re
import sys

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   'gm9', 'scripts', 'dump_system_apps.gm9')
MAX_WIDTH = 40  # characters per line in prompts, so text isn't cut off

titles = [
 ("00040030","00008202","HOME Menu","HOME Menu"),
 ("00040010","00020000","System Settings","System Settings"),
]
n = len(titles)
def screen(i, verb, name):
    bar = "[" + "#" * i + "." * (n - i) + "]"
    return f'set PREVIEW_MODE "Dumping system apps\\n \\n{bar}\\n{i} of {n}\\n \\n{verb}:\\n{name}"'
out = [f"""# dump_system_apps.gm9
# SPDX-License-Identifier: GPL-3.0-or-later
# Generated by tools/gen_dump_script.py: edit that, then regenerate.
#
# Copies the .app files of the Japanese HOME Menu and System Settings from
# SysNAND to 0:/gm9/out/3ds-jpn-english/<titleid>/ and decrypts the copies
# there.
# Read-only on system memory: it only reads from 1:/title and only writes
# to the SD card. Only .app files are copied (no .tmd or cmd folder).
#
# Each file is copied as <name>.app.part, decrypted, then renamed to
# <name>.app, so a file named .app is always complete and decrypted.
# If earlier dumps exist, you're asked once whether to redo them or skip
# finished ones. An app counts as finished only if every .app the console
# currently has for it is present, so interrupted dumps, deleted files and
# newer versions after a system update are always redone.
# At the end, it lists which apps were copied fresh, kept from an\n# earlier run, or not installed.

set DST 0:/gm9/out/3ds-jpn-english
set NONE 0:/gm9/out/3ds-jpn-english/__nothing__
set ABSENT ""
set NEW ""
set KEPT ""
set MODE redo
set ERRORMSG "Script stopped. Nothing on the\\nconsole was changed. Note the\\nfile shown and open an issue\\non GitHub."

ask "Copy and decrypt {n} system apps\\nto 0:/gm9/out/3ds-jpn-english?\\n \\nThis only reads system memory."
if find $[DST]/* NULL
if ask "Files from an earlier run are\\nalready in gm9/out/3ds-jpn-english.\\n \\nDump those apps again?\\n \\nYes: replace them with fresh copies.\\nNo: keep them and skip them."
set MODE redo
else
set MODE skip
end
end
mkdir -o -s $[DST]
"""]
for i, (hi, lo, name, short) in enumerate(titles, 1):
    d = f"$[DST]/{hi}{lo}"
    src = f"1:/title/{hi}/{lo}/content"
    out.append(f"""
# {i}. {name}
set DO 1
set WORK $[NONE]
set CHECK $[NONE]
if chk $[MODE] "skip"
if find {d} NULL
if find {src} NULL
set DO 0
set CHECK {src}
end
end
end
for -o -s $[CHECK] *.app
    strsplit APPNAME $[FORPATH] "/"
    if not find {d}/$[APPNAME] NULL
    set DO 1
    end
next
if chk $[DO] "0"
set KEPT "$[KEPT]\\n{short}"
{screen(i, "Already done, skipping", name)}
end
if chk $[DO] "1"
if find {src} NULL
if find {d} NULL
{screen(i, "Clearing old copy (SD card only)", name)}
rm -o -s {d}
end
{screen(i, "Copying and decrypting", name)}
set WORK {src}
else
set ABSENT "$[ABSENT]\\n{short}"
set DO 0
end
end
for -o -s $[WORK] *.app
    strsplit APPNAME $[FORPATH] "/"
    cp -s -w $[FORPATH] {d}/$[APPNAME].part
    decrypt {d}/$[APPNAME].part
    mv -w {d}/$[APPNAME].part {d}/$[APPNAME]
next
if chk $[DO] "1"
set NEW "$[NEW]\\n{short}"
end""")
out.append(f"""
set PREVIEW_MODE "Dumping system apps\\n \\n[{'#'*n}]\\n{n} of {n}\\n \\nAll done.\\nSummary on the bottom screen."
if chk -u "$[NEW]" ""
echo "Copied and decrypted fresh:\\n$[NEW]"
end
if chk -u "$[KEPT]" ""
echo "Already done, kept from earlier:\\n$[KEPT]"
end
if chk -u "$[ABSENT]" ""
echo "Not installed on this console:\\n$[ABSENT]"
end
set SUCCESSMSG "Done. Decrypted files are in\\n0:/gm9/out/3ds-jpn-english"
""")
script = "\n".join(out)


def check(text):
    """Return a list of problems in the generated script."""
    problems, stack = [], []
    for no, line in enumerate(text.split("\n"), 1):
        code = line.strip()
        if not code or code.startswith("#"):
            continue
        where = f"line {no}: {code[:60]}"
        if code.count('"') % 2:
            problems.append(f"{where}: unbalanced quotes")
        word = code.split()[0]
        if word == "for":
            if stack:
                problems.append(f"{where}: 'for' inside {stack[-1]!r} (GodMode9 doesn't allow it)")
            stack.append("for")
        elif word == "next":
            if not stack or stack.pop() != "for":
                problems.append(f"{where}: 'next' without 'for'")
        elif word == "if":
            stack.append("if")
        elif word == "else":
            if not stack or stack[-1] != "if":
                problems.append(f"{where}: 'else' without 'if'")
        elif word == "end":
            if not stack or stack.pop() != "if":
                problems.append(f"{where}: 'end' without 'if'")
        for text_ in re.findall(r'"([^"]*)"', code):
            for part in text_.split("\\n"):
                visible = re.sub(r"\$\[[A-Z_]+\]", "", part)
                if len(visible) > MAX_WIDTH:
                    problems.append(f"{where}: prompt line over {MAX_WIDTH} characters: {part!r}")
    if stack:
        problems.append(f"unclosed blocks at end of script: {stack}")
    return problems


def main(argv):
    problems = check(script)
    for p in problems:
        print(p)
    if problems:
        print(f"{len(problems)} problems; script not written.")
        return 1
    if "--check" in argv:
        try:
            current = open(OUT, encoding="utf-8").read()
        except OSError:
            current = None
        if current != script:
            print(f"{OUT} is out of date: run python3 -m tools.gen_dump_script")
            return 1
        print("dump script checks passed and the committed script is up to date.")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(script)
    print(f"checks passed; wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
